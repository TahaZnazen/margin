import {
  fillVisibility,
  minPairDistance,
  PAGE_DIM_BRIGHTNESS,
  PAGE_INVERT_AMOUNT,
  PAGE_MODES,
  PAGE_TINT_SEPIA,
  SAMPLES,
  TEXT_INKS,
  textContrast,
  underlineContrast,
  VISIONS,
} from "./analysis";
import { FILL_DARK_ALPHA, HIGHLIGHT_COLORS, HIGHLIGHT_PALETTE } from "./palette";

/** Minimums the palette must meet; palette.test.ts enforces them. */
export const PALETTE_REQUIREMENTS = {
  /** WCAG 1.4.3 (AA) for page text under any highlight. */
  textContrast: 4.5,
  /** WCAG 1.4.11 for the underline as a graphical object against the page. */
  underlineContrast: 3,
  /** The highlight must be clearly visible on its page (OKLab distance from bare paper). */
  fillVisibility: 0.06,
  /**
   * Smallest OKLab distance between any two of the five colors, for every vision type.
   * 0.02 is roughly a just-noticeable difference; 0.04 keeps neighbours apart at a glance.
   */
  pairDistance: 0.04,
} as const;

const f2 = (n: number) => n.toFixed(2);
const f3 = (n: number) => n.toFixed(3);

/** Markdown report of every palette measurement. Kept in sync as a file snapshot. */
export function renderPaletteReport(): string {
  const lines: string[] = [];
  const row = (cells: string[]) => lines.push(`| ${cells.join(" | ")} |`);

  lines.push("<!-- Generated by packages/ui/src/highlight/palette.test.ts. Do not edit. -->");
  lines.push("<!-- Regenerate: UPDATE_PALETTE_DOC=1 pnpm test packages/ui -->");
  lines.push("");
  lines.push("# Highlight palette: measurements");
  lines.push("");
  lines.push("## Swatches");
  lines.push("");
  row([
    "Color",
    "Meaning",
    "Key",
    "Fill light/sepia (multiply)",
    `Fill dark (normal, α ${FILL_DARK_ALPHA})`,
    "Underline light",
    "Underline dark",
    "Chip light",
    "Chip dark",
  ]);
  row(Array(9).fill("---"));
  for (const c of HIGHLIGHT_COLORS) {
    const s = HIGHLIGHT_PALETTE[c];
    row(
      [
        `${s.label} (\`${c}\`)`,
        s.meaning,
        s.shortcut,
        s.fillLight,
        s.fillDark,
        s.underlineLight,
        s.underlineDark,
        s.chipLight,
        s.chipDark,
      ].map((v) => v),
    );
  }
  lines.push("");
  lines.push("## Page models");
  lines.push("");
  lines.push(`- **light**: white paper, text inks ${TEXT_INKS.join(" and ")}.`);
  lines.push(`- **sepia**: the page is multiplied by ${PAGE_TINT_SEPIA}.`);
  lines.push(`- **dark-dimmed**: the page at \`brightness(${PAGE_DIM_BRIGHTNESS})\`.`);
  lines.push(
    `- **dark-inverted**: the page at \`invert(${PAGE_INVERT_AMOUNT}) hue-rotate(180deg)\`.`,
  );
  lines.push("");
  lines.push(
    `## Text contrast under the highlight (min over inks; required ≥ ${PALETTE_REQUIREMENTS.textContrast}:1)`,
  );
  lines.push("");
  row(["Color", ...PAGE_MODES]);
  row(Array(PAGE_MODES.length + 1).fill("---"));
  for (const c of HIGHLIGHT_COLORS)
    row([c, ...PAGE_MODES.map((m) => `${f2(textContrast(c, m))}:1`)]);
  lines.push("");
  lines.push(
    `## Underline contrast against the page (required ≥ ${PALETTE_REQUIREMENTS.underlineContrast}:1)`,
  );
  lines.push("");
  row(["Color", ...PAGE_MODES]);
  row(Array(PAGE_MODES.length + 1).fill("---"));
  for (const c of HIGHLIGHT_COLORS)
    row([c, ...PAGE_MODES.map((m) => `${f2(underlineContrast(c, m))}:1`)]);
  lines.push("");
  lines.push(
    `## Fill visibility: ΔE_OK between highlighted and bare paper (required ≥ ${PALETTE_REQUIREMENTS.fillVisibility})`,
  );
  lines.push("");
  row(["Color", ...PAGE_MODES]);
  row(Array(PAGE_MODES.length + 1).fill("---"));
  for (const c of HIGHLIGHT_COLORS) row([c, ...PAGE_MODES.map((m) => f3(fillVisibility(c, m)))]);
  lines.push("");
  lines.push(
    `## Distinguishability: smallest pairwise ΔE_OK (required ≥ ${PALETTE_REQUIREMENTS.pairDistance})`,
  );
  lines.push("");
  lines.push(
    "Simulation: Machado, Oliveira & Fernandes (2009) at full severity. Cell = smallest distance and the closest pair.",
  );
  lines.push("");
  row(["Rendered as", ...VISIONS]);
  row(Array(VISIONS.length + 1).fill("---"));
  for (const [name, sample] of Object.entries(SAMPLES)) {
    row([
      name,
      ...VISIONS.map((v) => {
        const d = minPairDistance(sample, v);
        return `${f3(d.deltaE)} (${d.a}/${d.b})`;
      }),
    ]);
  }
  lines.push("");
  return lines.join("\n");
}
